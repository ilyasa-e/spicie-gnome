import GLib from 'gi://GLib';
import GdkPixbuf from 'gi://GdkPixbuf';
import Gio from 'gi://Gio';
import Cairo from 'cairo';
import { isLyricsWindow, activeVocalLines, hideLyricsWindowFromLists } from '../lyricsPresentation.js';
import { displayLineIndex } from '../karaokeTiming.js';
import { LyricsSync } from '../lyricsSync.js';
import { FloatingLyricsHUDApp, inputRegion } from '../bin/spotify-floating-hud';
let count=0;
const check=(name,value)=>{if(!value)throw Error(name);print(`PASS ${name}`);count++;};
const prefs={get_title:()=> 'Spicie',get_gtk_application_id:()=> 'org.gnome.Extensions',get_wm_class:()=> 'org.gnome.Extensions'};
check('Preferences with the same title are never treated as lyrics',!isLyricsWindow(prefs));
check('Only the lyrics application identity is accepted',isLyricsWindow({...prefs,get_gtk_application_id:()=> 'dev.norang.SpotifyFloatingLyricsHUD'}));
let hidden=0;
check('Preferences with the same title are never hidden from window lists',!hideLyricsWindowFromLists({...prefs,hide_from_window_list:()=>hidden++})&&hidden===0);
const overlay={...prefs,get_gtk_application_id:()=> 'dev.norang.SpotifyFloatingLyricsHUD',hide_from_window_list:()=>hidden++};
check('Current GNOME window-list control hides only the lyrics window',hideLyricsWindowFromLists(overlay)&&hidden===1);
const legacy={...overlay,hide_from_window_list:undefined};
check('Older GNOME uses the owning Wayland client',hideLyricsWindowFromLists(legacy,{owns_window:win=>win===legacy,hide_from_window_list:()=>hidden++})&&hidden===2);
check('A different client cannot hide an unrelated window',!hideLyricsWindowFromLists(legacy,{owns_window:()=>false,hide_from_window_list:()=>hidden++})&&hidden===2);
const lines=[{timeMs:0,startTimeMs:0,endTimeMs:5000,words:'First',syllables:[{text:'First',startTimeMs:2000,endTimeMs:5000}]},{timeMs:8000,endTimeMs:10000,words:'Next'}];
check('First line stays hidden until its first timed word',displayLineIndex(lines,1000)===-1&&activeVocalLines(lines,1000).length===0);
check('Started line is held through a gap',displayLineIndex(lines,6000)===0);
check('Next line replaces the held line at its start',displayLineIndex(lines,8000)===1);
const sync=new LyricsSync(lines);sync.updatePosition(3000);sync.updatePosition(6000);
check('Top bar synchronization does not clear the line between phrases',sync.getCurrentIndex()===0);
sync.updatePosition(0);check('Seeking before the first word clears the held line',sync.getCurrentIndex()===-1);
sync.setLyrics([]);check('Track changes clear previous lyrics',sync.getLines().length===0);sync.destroy();
const app=new FloatingLyricsHUDApp();
const surface=new Cairo.ImageSurface(Cairo.Format.ARGB32,100,100),cr=new Cairo.Context(surface);
app._drawBackdrop(cr,100,100,'transparent');
const dir=GLib.dir_make_tmp('spicie-transparent-XXXXXX'),path=dir+'/background.png';surface.writeToPNG(path);
const pixbuf=GdkPixbuf.Pixbuf.new_from_file(path);const pixels=pixbuf.get_pixels();
check('Transparent background has no dark tint or opaque pixels',pixbuf.has_alpha&&pixels.every((value,i)=>i%4!==3||value===0));
app._settings={get_string:key=>({'background-style':'transparent','font-family':'Sans','lyrics-alignment':'center'}[key]||''),get_int:key=>key==='font-size'?22:key==='floating-line-count'?1:14,get_boolean:()=>true};
app._lines=lines;app._basePositionMs=1000;app._hasStdinLyrics=true;
let drawn=[];app._drawTextLine=(_cr,text)=>{drawn.push(text);return 20;};app._drawKaraokeLine=(_cr,line)=>{drawn.push(line.words);return 20;};
app._render(cr,400,100);check('Floating lyrics preview the first lyric while waiting',drawn.includes('First'));drawn=[];
app._rowMotion=null;app._basePositionMs=3000;app._render(cr,400,100);check('Floating lyrics show only started words without a future-line preview',drawn.length===1&&drawn[0]==='First');
const drawingApp=new FloatingLyricsHUDApp();drawingApp._settings=app._settings;
drawingApp._drawKaraokeLine(cr,lines[0],lines[0].words,3000,'Sans',22,0,0,400);
const activeCache=drawingApp._karaokeCache;
drawingApp._drawKaraokeLine(cr,lines[1],lines[1].words,3000,'Sans',22,0,40,400,false);
check('Context lines do not replace the active karaoke cache',drawingApp._karaokeCache===activeCache&&drawingApp._karaokeLayouts.get(lines[1]).drawing.characters===null);
drawingApp._karaokeCache=null;
drawingApp._drawKaraokeLine(cr,lines[1],lines[1].words,3000,'Sans',22,0,40,400,false);
check('Context-only frames render without an active lyric cache',drawingApp._karaokeCache===null);
drawingApp._shutdown();
check('Click-through off accepts input without passing null to GDK',inputRegion(false).numRectangles()===1);
check('Click-through on uses an empty input region',inputRegion(true).numRectangles()===0);
const pendingApp=new FloatingLyricsHUDApp();let fallback=0;pendingApp._loadTrack=()=>fallback++;
pendingApp._handleIPCMessage(JSON.stringify({type:'lyrics',title:'Old',lines}));
pendingApp._handleIPCMessage(JSON.stringify({type:'lyrics',title:'New',lines:[],pending:true}));
check('A song change hides the previous lyrics while the next set loads',pendingApp._lines.length===0&&pendingApp._pending);
check('Loading lyrics keep the extension in charge instead of a second fetch',pendingApp._hasStdinLyrics&&fallback===0);
pendingApp._handleIPCMessage(JSON.stringify({type:'lyrics',title:'New',lines:[]}));
check('A definitive empty answer still starts the window fallback',!pendingApp._hasStdinLyrics&&fallback===1&&!pendingApp._pending);
pendingApp._shutdown();
app._shutdown();cr.$dispose();Gio.File.new_for_path(path).delete(null);Gio.File.new_for_path(dir).delete(null);
print(`${count} regression checks passed`);
