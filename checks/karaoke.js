function digest(drawing, time, name) {
    const surface = new Cairo.ImageSurface(Cairo.Format.ARGB32, 280, 160);
    const cr = new Cairo.Context(surface);
    cr.setSourceRGB(0, 0, 0); cr.paint();
    drawing.draw(cr, time, 8, 8);
    surface.writeToPNG(`${folder}/${name}.png`);
    cr.$dispose();
    const bytes = GLib.file_get_contents(`${folder}/${name}.png`)[1];
    return GLib.compute_checksum_for_data(GLib.ChecksumType.SHA256, bytes);
}
